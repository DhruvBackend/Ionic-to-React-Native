#!/usr/bin/env node
// Writes src/assets/client/homeImages.ts: the client's Home screen SVGs (Ionic assets/imgs/*.svg used by home.html),
// embedded as text so react-native-svg can draw them without a Metro transformer (same approach as tabIcons.ts).
//   node scripts/gen-home-images.mjs [client-id]      (default: topbath)
// NOTE: written by the Home implementer; the lead should fold this into scripts/use-client.mjs.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const id = process.argv[2] || 'topbath';
const dir = path.join(ROOT, 'clients', id, 'assets', 'home-images');
const images = {};
for (const f of fs.readdirSync(dir).filter(n => n.endsWith('.svg')).sort()) {
  const xml = fs.readFileSync(path.join(dir, f), 'utf8');
  // Intrinsic ratio of an <img src=svg>: width/height attributes (px, pt), else the viewBox.
  const num = re => { const m = xml.match(re); return m ? parseFloat(m[1]) : NaN; };
  const svgTag = xml.match(/<svg[^>]*>/)[0];
  let w = parseFloat((svgTag.match(/\swidth="([\d.]+)/) || [])[1]);
  let h = parseFloat((svgTag.match(/\sheight="([\d.]+)/) || [])[1]);
  if (!(w > 0 && h > 0)) {
    const vb = (svgTag.match(/viewBox="([^"]+)"/) || [])[1]?.trim().split(/[\s,]+/).map(Number);
    w = vb?.[2]; h = vb?.[3];
  }
  images[path.basename(f, '.svg')] = { xml, ratio: w / h, css: /<style/.test(xml) };
}
fs.writeFileSync(
  path.join(ROOT, 'src/assets/client/homeImages.ts'),
  `// GENERATED by scripts/gen-home-images.mjs from clients/${id}/assets/home-images. Do not edit by hand.\nexport const homeImages: Record<string, { xml: string; ratio: number; css: boolean }> = ${JSON.stringify(images, null, 2)};\n`,
);
console.log('gen-home-images:', Object.keys(images).join(', '));
