#!/usr/bin/env node
// Writes src/api/fixtures.generated.ts: a static import of every endpoint fixture, because Metro
// can't load files by dynamic path. Also checks each fixture file (plan Task 5).
//
//   node scripts/gen-fixtures.mjs [--dir <fixtures dir>] [--out <generated .ts file>]
//
// Files starting with "_" (e.g. _sessions.json) are shared data, not endpoint fixtures, and are skipped.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SERVERS = ['root', 'sfa', 'server_url'];

function arg(name, fallback) {
  const i = process.argv.indexOf(name);
  return i > -1 && process.argv[i + 1] ? path.resolve(process.argv[i + 1]) : fallback;
}
const dir = arg('--dir', path.join(ROOT, 'src/api/fixtures'));
const out = arg('--out', path.join(ROOT, 'src/api/fixtures.generated.ts'));

const errors = [];
const files = fs.existsSync(dir)
  ? fs.readdirSync(dir).filter(f => f.endsWith('.json') && !f.startsWith('_')).sort()
  : [];

for (const file of files) {
  let f;
  try {
    f = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'));
  } catch (e) {
    errors.push(`${file}: not valid JSON (${e.message})`);
    continue;
  }
  if (typeof f.endpoint !== 'string' || !f.endpoint) {
    errors.push(`${file}: "endpoint" missing`);
    continue;
  }
  const expected = f.endpoint.replace(/\//g, '__') + '.json';
  if (file !== expected) errors.push(`${file}: endpoint "${f.endpoint}" must live in ${expected}`);
  if (!SERVERS.includes(f.server)) errors.push(`${file}: "server" must be one of ${SERVERS.join(', ')}`);
  if (!f.variants || typeof f.variants !== 'object' || !('default' in f.variants)) {
    errors.push(`${file}: "variants.default" missing`);
  } else {
    for (const [k, v] of Object.entries(f.variants)) {
      if (!v || typeof v !== 'object' || !('$httpError' in v)) continue;
      const ok = Number.isInteger(v.$httpError) && v.$httpError >= 400 && v.$httpError <= 599 && Object.keys(v).every(x => x === '$httpError' || x === 'body');
      if (!ok) errors.push(`${file}: variant "${k}": "$httpError" must be an integer 400-599 and may only be accompanied by "body"`);
    }
  }
  if (f.variants && 'default' in f.variants && !('malformed' in f.variants)) {
    console.warn(`gen-fixtures: ${file} has no "malformed" variant (required once a screen uses it)`);
  }
}

if (errors.length) {
  console.error(`gen-fixtures: invalid fixtures:\n  ${errors.join('\n  ')}`);
  process.exit(1);
}

let rel = path.relative(path.dirname(out), dir).split(path.sep).join('/');
if (!rel.startsWith('.')) rel = './' + rel;
const imports = files.map((f, i) => `import f${i} from '${rel}/${f}';`).join('\n');
const list = files.map((_, i) => `f${i}`).join(', ');

fs.writeFileSync(
  out,
  `// GENERATED by scripts/gen-fixtures.mjs from src/api/fixtures/*.json. Do not edit by hand.\n` +
    `import type { FixtureFile } from './mock';\n` +
    (imports ? imports + '\n' : '') +
    `\nexport const fixtureFiles = [${list}] as FixtureFile[];\n`,
);
console.log(`gen-fixtures: ${files.length} fixture(s) → ${path.relative(ROOT, out)}`);
