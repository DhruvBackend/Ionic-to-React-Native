#!/usr/bin/env node
// Writes src/navigation/routes.generated.ts from every src/screens/<Name>/{route.ts,index.tsx}.
// Screens register themselves this way, so parallel screen agents never edit one shared file.
//
//   node scripts/gen-routes.mjs [--dir <screens dir>] [--out <generated .ts file>]
//
// Folders starting with "_" are shared helpers, not screens, and are skipped. So are folders that have neither
// route.ts nor index.tsx (only a card.md from scripts/screen-card.mjs: not ported yet).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function arg(name, fallback) {
  const i = process.argv.indexOf(name);
  return i > -1 && process.argv[i + 1] ? path.resolve(process.argv[i + 1]) : fallback;
}
const dir = arg('--dir', path.join(ROOT, 'src/screens'));
const out = arg('--out', path.join(ROOT, 'src/navigation/routes.generated.ts'));
// Phase 2 kit (2026-11-03): reachable Ionic pages (inventory LIVE / PUSH-ONLY) that are not ported yet get a placeholder
// route, so ported screens can push their real targets. Tabs is the tab navigator itself, not a page route.
const inventoryFile = arg('--inventory', path.join(ROOT, 'docs/inventory.json'));
const MODAL_PAGES = new Set(JSON.parse(fs.readFileSync(path.join(ROOT, 'src/navigation/ionicModalPages.json'), 'utf8')));
const NOT_A_PAGE_ROUTE = new Set(['Tabs']);

const errors = [];
const screens = fs.existsSync(dir)
  ? fs
      .readdirSync(dir, { withFileTypes: true })
      .filter(d => d.isDirectory() && !d.name.startsWith('_'))
      .filter(d => ['route.ts', 'index.tsx'].some(f => fs.existsSync(path.join(dir, d.name, f))))
      .map(d => d.name)
      .sort()
  : [];

for (const name of screens) {
  const routeFile = path.join(dir, name, 'route.ts');
  if (!fs.existsSync(routeFile)) {
    errors.push(`${name}: route.ts missing`);
    continue;
  }
  if (!fs.existsSync(path.join(dir, name, 'index.tsx'))) errors.push(`${name}: index.tsx missing`);
  const m = fs.readFileSync(routeFile, 'utf8').match(/name:\s*['"]([^'"]+)['"]/);
  if (!m) errors.push(`${name}: route.ts has no name`);
  else if (m[1] !== name) errors.push(`${name}: route.ts name "${m[1]}" must equal the folder name`);
  const modal = /presentation:\s*['"]modal['"]/.test(fs.readFileSync(routeFile, 'utf8'));
  if (modal !== MODAL_PAGES.has(name))
    errors.push(`${name}: presentation must be ${MODAL_PAGES.has(name) ? "'modal'" : "'card'"} (src/navigation/ionicModalPages.json)`);
}

if (errors.length) {
  console.error(`gen-routes: invalid screens:\n  ${errors.join('\n  ')}`);
  process.exit(1);
}

let rel = path.relative(path.dirname(out), dir).split(path.sep).join('/');
if (!rel.startsWith('.')) rel = './' + rel;
const imports = screens
  .map((name, i) => `import r${i} from '${rel}/${name}/route';\nimport C${i} from '${rel}/${name}';`)
  .join('\n');
const inventory = fs.existsSync(inventoryFile) ? JSON.parse(fs.readFileSync(inventoryFile, 'utf8')) : [];
const ported = new Set(screens);
const placeholders = (Array.isArray(inventory) ? inventory : inventory.screens || [])
  .filter(s => (s.status === 'LIVE' || s.status === 'PUSH-ONLY') && !ported.has(s.name) && !NOT_A_PAGE_ROUTE.has(s.name))
  .map(s => s.name)
  .sort()
  .map(name => ({ name, presentation: MODAL_PAGES.has(name) ? 'modal' : 'card' }));
const list = screens.map((_, i) => `  { ...r${i}, component: C${i} },`).join('\n');

fs.writeFileSync(
  out,
  `// GENERATED by scripts/gen-routes.mjs from src/screens/*/route.ts. Do not edit by hand.\n` +
    `import type { RouteDef } from './types';\n` +
    (imports ? imports + '\n' : '') +
    (list ? `\nexport const routes: RouteDef[] = [\n${list}\n];\n` : `\nexport const routes: RouteDef[] = [];\n`) +
    `\n// Reachable Ionic pages not ported yet (docs/inventory.json); RootNavigator registers a placeholder for each.\n` +
    `export const placeholderRoutes: { name: string; presentation: 'card' | 'modal' }[] = ${JSON.stringify(placeholders)};\n`,
);
console.log(`gen-routes: ${screens.length} screen(s), ${placeholders.length} placeholder(s) → ${path.relative(ROOT, out)}`);
