#!/usr/bin/env node
// Selects which client app this codebase builds (white-label, plan Task 3).
//
//   node scripts/use-client.mjs <id> [--skip-assets]   generate files for clients/<id>/client.json
//   node scripts/use-client.mjs --validate <file>      only check a client.json against the schema
//
// Writes:
//   src/config/client.ts         typed config imported by the app (committed for topbath)
//   android/client.properties    applicationId / versionName / versionCode / appName read by Gradle (git-ignored)
//   src/i18n/client/<lang>.json  translation overrides from clients/<id>/i18n ({} when none)
//   src/assets/client/*          logo + banner used by screens
//   android/.../mipmap-*/        launcher icons, copied unchanged from the Ionic resources (1:1)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv from 'ajv';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CLIENTS = path.join(ROOT, 'clients');
const DENSITIES = ['ldpi', 'mdpi', 'hdpi', 'xhdpi', 'xxhdpi', 'xxxhdpi'];
const SCREEN_ASSETS = ['logo.png', 'banner.png'];
const LANGUAGES = ['en', 'hin', 'nep', 'es'];

function fail(msg) {
  console.error(`use-client: ${msg}`);
  process.exit(1);
}

function validate(config) {
  const schema = JSON.parse(fs.readFileSync(path.join(CLIENTS, 'client.schema.json'), 'utf8'));
  const ajv = new Ajv({ allErrors: true });
  const ok = ajv.validate(schema, config);
  return ok ? [] : ajv.errors.map(e => `${e.instancePath || '(root)'} ${e.message}`);
}

function readJson(file) {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch (e) {
    fail(`cannot read ${file}: ${e.message}`);
  }
}

function writeFile(rel, content) {
  const file = path.join(ROOT, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}

function generate(id, { skipAssets }) {
  const file = path.join(CLIENTS, id, 'client.json');
  if (!fs.existsSync(file)) fail(`unknown client "${id}" (no ${path.relative(ROOT, file)})`);
  const config = readJson(file);
  const errors = validate(config);
  if (errors.length) fail(`invalid ${path.relative(ROOT, file)}:\n  ${errors.join('\n  ')}`);
  if (config.id !== id) fail(`client.json id "${config.id}" does not match folder "${id}"`);

  writeFile(
    'src/config/client.ts',
    `// GENERATED by scripts/use-client.mjs from clients/${id}/client.json. Do not edit by hand.\n` +
      `import type { ClientConfig } from './types';\n\n` +
      `export const client: ClientConfig = ${JSON.stringify(config, null, 2)};\n`,
  );

  writeFile(
    'android/client.properties',
    `# GENERATED by scripts/use-client.mjs (${id}). Read by android/app/build.gradle.\n` +
      `applicationId=${config.androidPackage}\n` +
      `versionName=${config.versionName}\n` +
      `versionCode=${config.versionCode}\n` +
      `appName=${config.appName}\n`,
  );

  writeI18nOverrides(config.assetsFrom || id);
  if (!skipAssets) copyAssets(config.assetsFrom || id);
  console.log(`use-client: ${id} selected (${config.androidPackage} ${config.versionName})`);
}

// Every language always gets a file (src/i18n/index.ts imports all four); {} means "no override".
function writeI18nOverrides(sourceId) {
  for (const lang of LANGUAGES) {
    const from = path.join(CLIENTS, sourceId, 'i18n', `${lang}.json`);
    const content = fs.existsSync(from) ? readJson(from) : {};
    writeFile(`src/i18n/client/${lang}.json`, JSON.stringify(content, null, 2) + '\n');
  }
}

function copyAssets(assetsId) {
  const src = path.join(CLIENTS, assetsId, 'assets');
  if (!fs.existsSync(src)) fail(`missing assets folder ${path.relative(ROOT, src)}`);

  for (const name of SCREEN_ASSETS) {
    const from = path.join(src, name);
    if (!fs.existsSync(from)) fail(`missing asset ${path.relative(ROOT, from)}`);
    fs.mkdirSync(path.join(ROOT, 'src/assets/client'), { recursive: true });
    fs.copyFileSync(from, path.join(ROOT, 'src/assets/client', name));
  }

  // Ionic had only a square icon (no roundIcon), so the round slot gets the same image:
  // launchers that prefer roundIcon then show exactly what they show for the Ionic app.
  for (const dpi of DENSITIES) {
    const from = path.join(src, 'android-icon', `drawable-${dpi}-icon.png`);
    if (!fs.existsSync(from)) continue;
    const dir = path.join(ROOT, 'android/app/src/main/res', `mipmap-${dpi}`);
    fs.mkdirSync(dir, { recursive: true });
    fs.copyFileSync(from, path.join(dir, 'ic_launcher.png'));
    fs.copyFileSync(from, path.join(dir, 'ic_launcher_round.png'));
  }
}

const args = process.argv.slice(2);
if (args[0] === '--validate') {
  if (!args[1]) fail('usage: use-client.mjs --validate <client.json>');
  const errors = validate(readJson(path.resolve(args[1])));
  if (errors.length) fail(`invalid ${args[1]}:\n  ${errors.join('\n  ')}`);
  console.log(`use-client: ${args[1]} is valid`);
} else if (args[0] && !args[0].startsWith('--')) {
  generate(args[0], { skipAssets: args.includes('--skip-assets') });
} else {
  fail('usage: use-client.mjs <client-id> [--skip-assets] | --validate <client.json>');
}
