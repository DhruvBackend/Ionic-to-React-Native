#!/usr/bin/env bash
# Generates a Markdown inventory of an Ionic 3 app: every page (incl. nested sub-pages),
# its size and the API endpoints it calls, plus base URLs, storage keys and native plugins.
# Usage: bash scripts/ionic-inventory.sh <path-to-ionic-repo>/src > docs/INVENTORY.md
# Reused for every Basiq/Abacusdesk app, so later ports can be diffed against Top Bath.
set -euo pipefail
SRC="${1:?usage: ionic-inventory.sh <ionic-src-dir>}"
cd "$SRC"

endpoints() {  # endpoints called from the .ts files in a page folder
  grep -ohE "(onPostRequestDataFromApi|onGetRequestDataFromApi|post_rqst|get_rqst)\([^,]*,\s*['\"][^'\"]+['\"]" "$1"/*.ts 2>/dev/null \
    | grep -oE "['\"][^'\"]+['\"]$" | tr -d "'\"" | grep "/" | sort -u | tr '\n' ' ' || true
}
row() {  # one table row for a page folder
  local html ts
  html=$(cat "$1"/*.html 2>/dev/null | wc -l); ts=$(cat "$1"/*.ts 2>/dev/null | wc -l)
  echo "| \`$1\` | $html | $ts | $(endpoints "$1") |"
}

echo "# Ionic app inventory"
echo
echo "Generated by \`scripts/ionic-inventory.sh\` on $(date +%F). Endpoint list shows only path-like strings found in the page's .ts files."
echo
echo "## Pages"
echo
echo "| Page | HTML lines | TS lines | Endpoints |"
echo "|---|---|---|---|"
total=0
for d in pages/*/; do
  d=${d%/}
  if ls "$d"/*.ts >/dev/null 2>&1; then row "$d"; total=$((total+1))
  else for s in "$d"/*/; do row "${s%/}"; total=$((total+1)); done; fi
done
echo
echo "**Total screens: $total**"
echo
echo "## Base URLs (providers/dbservice)"
echo
echo '```'
grep -nE "https?://" providers/dbservice/dbservice.ts | sed -E 's/[[:space:]]+$//' || true
echo '```'
echo
echo "## Storage keys"
echo
grep -rhoE "storage\.(get|set|remove)\(['\"][^'\"]+" . | sed -E "s/storage\.(get|set|remove)\(['\"]//" | sort -u | sed 's/^/- `/;s/$/`/'
echo
echo "## Native plugins (@ionic-native)"
echo
grep -rhoE "from '@ionic-native/[^']+'" . | sed -E "s/from '@ionic-native\/([^']+)'/- \1/" | sort -u
echo
echo "## Languages"
echo
ls assets/i18n | sed 's/^/- /'
