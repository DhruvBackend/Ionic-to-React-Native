#!/usr/bin/env node
// Prints docs/INVENTORY.md: one row per Ionic page with status, roles, backend, feature and phase from
// docs/inventory.json, plus the older columns (HTML/TS line counts, endpoints) and the base URL, storage key,
// native plugin and language lists the first inventory had.
//
//   node scripts/inventory-md.mjs > docs/INVENTORY.md
//
// IONIC_SRC (env) defaults to C:/Migrations/Topbath_App_loyalty/src. Run scripts/build-inventory.mjs first.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { IONIC_SRC, read, maskTs, findApiCalls, walk } from './lib/ionic-scan.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rows = JSON.parse(fs.readFileSync(path.join(ROOT, 'docs/inventory.json'), 'utf8'));
const ALL_ROLES = ['Plumber', 'Sales_Boy', 'Dealer', 'Sales_Executive', 'Customer', 'Retailer'];

const roleText = roles => (ALL_ROLES.every(r => roles.includes(r)) ? 'all CMS roles' : roles.join(', '));
const esc = s => String(s).replace(/\|/g, '\\|');

function pageStats(row) {
  const dir = `${IONIC_SRC}/${row.ionicPath.replace(/^src\//, '')}`;
  const files = fs.readdirSync(dir).filter(f => fs.statSync(`${dir}/${f}`).isFile());
  // same counting as the first inventory (`cat *.ts | wc -l`): newline characters, module files included
  const sum = pred => files.filter(pred).reduce((n, f) => n + read(`${dir}/${f}`).split('\n').length - 1, 0);
  const html = sum(f => f.endsWith('.html'));
  const ts = sum(f => f.endsWith('.ts'));
  const endpoints = new Set();
  for (const f of files.filter(f => f.endsWith('.ts') && !/\.(module|spec)\.ts$/.test(f))) {
    const { clean, masked } = maskTs(read(`${dir}/${f}`));
    for (const c of findApiCalls(clean, masked, f)) if (c.endpoint && !c.endpoint.startsWith('<')) endpoints.add(c.endpoint);
  }
  return { html, ts, endpoints: [...endpoints].sort().join(' ') };
}

const counts = s => rows.filter(r => r.status === s).length;
const out = [];
const w = (...l) => out.push(...l);

w('# Ionic app inventory', '');
w(
  'Generated by `scripts/inventory-md.mjs` from `docs/inventory.json` (reachability, built by `scripts/build-inventory.mjs`) and the Ionic source. Do not edit by hand.',
  '',
  `**Total screens: ${rows.length}** (LIVE ${counts('LIVE')}, PUSH-ONLY ${counts('PUSH-ONLY')}, DEAD ${counts('DEAD')}).`,
  '',
  '- **LIVE**: reachable from the app start or a role tab set in Topbath.',
  '- **PUSH-ONLY**: reached only from a push-notification handler (`app.component.ts`, `home.ts`).',
  '- **DEAD**: not reachable in Topbath today. Ported behind a feature flag (spec §6.3). The reason is in the last table.',
  '- **Backend**: `root` = `dd_api` (`db.rootUrl`), `sfa` = `crm/api/app` (`db.rootUrlSfa`), `both` = the page calls both. A page with no calls shows `root`.',
  '- **Roles** are traced with a heuristic: `*ngIf` conditions on `userStorageData.type` are honoured, other conditions are assumed true. Pre-login pages list every role. DEAD rows list the roles that would reach the page if the flag were on (`Employee`, `SFA`, `DrLogin` for the SFA module).',
  '',
);

w('## Pages', '', '| Page | Status | Roles | Backend | Feature | Phase | HTML lines | TS lines | Endpoints |', '|---|---|---|---|---|---|---|---|---|');
const byPath = [...rows].sort((a, b) => a.ionicPath.localeCompare(b.ionicPath) || a.name.localeCompare(b.name));
for (const r of byPath) {
  const s = pageStats(r);
  w(`| \`${r.ionicPath.replace(/^src\//, '')}\` (${r.name}) | ${r.status} | ${esc(roleText(r.roles))} | ${r.backend} | ${r.feature ?? ''} | ${r.phase} | ${s.html} | ${s.ts} | ${esc(s.endpoints)} |`);
}
w('');

w('## Why DEAD screens are unreachable in Topbath', '', '| Screen | Feature | Phase | Evidence (file:line, paths relative to `src/`) |', '|---|---|---|---|');
for (const r of rows.filter(x => x.status === 'DEAD').sort((a, b) => a.phase - b.phase || a.name.localeCompare(b.name))) {
  w(`| ${r.name} | ${r.feature} | ${r.phase} | ${esc(r.unreachableBecause)} |`);
}
w('');

w('## Base URLs (providers/dbservice)', '', '```');
const dbs = read(`${IONIC_SRC}/providers/dbservice/dbservice.ts`).split('\n');
dbs.forEach((l, i) => {
  if (/https?:\/\//.test(l)) out.push(`${i + 1}:${l.replace(/\s+$/, '')}`);
});
w('```', '');

const srcFiles = walk(IONIC_SRC).filter(f => /\.(ts|html)$/.test(f));
const all = srcFiles.map(read).join('\n');

w('## Storage keys', '');
const keys = new Set([...all.matchAll(/storage\.(?:get|set|remove)\(['"]([^'"]+)/g)].map(m => m[1]));
for (const k of [...keys].sort()) w(`- \`${k}\``);
w('');

w('## Native plugins (@ionic-native)', '');
const natives = new Set([...all.matchAll(/from '@ionic-native\/([^']+)'/g)].map(m => m[1]));
for (const n of [...natives].sort()) w(`- ${n}`);
w('');

w('## Languages', '');
const i18n = `${IONIC_SRC}/assets/i18n`;
if (fs.existsSync(i18n)) for (const f of fs.readdirSync(i18n).sort()) w(`- ${f}`);
w('');

process.stdout.write(out.join('\n'));
