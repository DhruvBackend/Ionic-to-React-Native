#!/usr/bin/env node
// Writes src/screens/<name>/card.md for one Ionic page, extracted mechanically from the Ionic source
// (plan Task 12). The Quirks and States sections are left empty for the orchestrator.
//
//   node scripts/screen-card.mjs <Name> [--out <dir>] [--stdout]
//
// <Name> is the Ionic page class without the "Page" suffix (misspellings kept), e.g. Otp, Home, Customeradd.
// IONIC_SRC (env) defaults to C:/Migrations/Topbath_App_loyalty/src. The Ionic repo is read-only.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  IONIC_SRC,
  read,
  lineCount,
  maskTs,
  stripHtmlComments,
  stripScssComments,
  findCalls,
  findApiCalls,
  findNavTargets,
  matchClose,
  lineOf,
  collapse,
  listPages,
} from './lib/ionic-scan.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const clip = (s, n = 220) => (s.length > n ? s.slice(0, n - 1) + '…' : s);
const cell = s => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const code = s => '`' + String(s).replace(/`/g, "'") + '`';

/** `ident = <expr>` assignment (object literals only) for an endpoint body that is a bare variable */
function findAssignment(clean, masked, ident) {
  const name = ident.replace(/^this\./, '').replace(/[.$]/g, '\\$&');
  const re = new RegExp(`(?:this\\.|\\b(?:let|const|var)\\s+)${name}\\s*(?::[^=;]+)?=\\s*(?=[{\\[])`, 'g');
  let m;
  while ((m = re.exec(masked))) {
    const open = m.index + m[0].length;
    const close = matchClose(masked, open);
    if (close > 0) return { text: collapse(clean.slice(open, close + 1)), line: lineOf(clean, open) };
  }
  return null;
}

export function buildCard(name, { src = IONIC_SRC } = {}) {
  const pages = listPages(src);
  const page = pages.find(p => p.name === name || p.ionicClass === name);
  if (!page) throw new Error(`screen-card: no Ionic page class "${name}Page" under ${src}/pages`);
  const dir = `${src}/${page.dir}`;
  const rel = f => path.posix.relative(src, f).replace(/^/, 'src/');
  const base = path.posix.basename(page.tsFile, '.ts');

  const files = fs
    .readdirSync(dir)
    .filter(f => fs.statSync(`${dir}/${f}`).isFile())
    .sort();
  const tsFiles = files.filter(f => f.endsWith('.ts') && !f.endsWith('.module.ts') && !f.endsWith('.spec.ts'));
  const htmlFiles = files.filter(f => f.endsWith('.html'));
  const scssFiles = files.filter(f => f.endsWith('.scss'));

  const out = [];
  const w = (...l) => out.push(...l);

  // inventory info, when available
  let inv = null;
  try {
    inv = JSON.parse(fs.readFileSync(path.join(ROOT, 'docs/inventory.json'), 'utf8')).find(r => r.ionicClass === page.ionicClass);
  } catch {
    /* inventory not generated yet */
  }

  w(`# ${page.name} (card)`, '', `Generated by \`scripts/screen-card.mjs\` from \`src/${page.dir}\` (Ionic class \`${page.ionicClass}\`). Do not hand-edit the generated sections; Quirks and States are filled in by the orchestrator.`, '');
  if (inv) {
    w(
      `- **Status:** ${inv.status} · **Phase:** ${inv.phase} · **Backend:** ${inv.backend} · **Feature:** ${inv.feature ?? 'none'}`,
      `- **Roles:** ${inv.roles.join(', ')}`,
      ...(inv.unreachableBecause ? [`- **Unreachable in Topbath because:** ${inv.unreachableBecause}`] : []),
      '',
    );
  }

  // 1. files
  w('## Ionic files', '', '| File | Lines |', '|---|---|');
  for (const f of files) w(`| ${code(rel(`${dir}/${f}`))} | ${lineCount(`${dir}/${f}`)} |`);
  w('');

  // parse sources
  const apis = [];
  const navs = [];
  const params = [];
  const overlays = [];
  const natives = new Set();
  const i18n = [];
  for (const f of tsFiles) {
    const raw = read(`${dir}/${f}`);
    const { clean, masked } = maskTs(raw);
    const file = rel(`${dir}/${f}`);
    for (const a of findApiCalls(clean, masked, file)) {
      if (a.body && /^(this\.)?[\w$.]+$/.test(a.body) && a.body !== "''" && !/^\d/.test(a.body)) a.bodyDef = findAssignment(clean, masked, a.body);
      apis.push(a);
    }
    for (const n of findNavTargets(clean, masked)) navs.push({ ...n, file });
    for (const c of findCalls(clean, masked, 'get')) {
      if (/navParams/i.test(c.recv)) params.push({ key: (c.args[0] || '').replace(/^['"]|['"]$/g, ''), file, line: c.line });
    }
    for (const m of clean.matchAll(/navParams\s*\.\s*data\b/g)) params.push({ key: '(navParams.data)', file, line: lineOf(clean, m.index) });
    for (const c of findCalls(clean, masked, 'create')) {
      const kind = (c.recv.match(/(alert|loading|toast|actionSheet)Ctrl/) || [])[1];
      if (kind) overlays.push({ kind: `${kind}Ctrl`, text: collapse(c.args[0] || ''), file, line: c.line });
    }
    for (const c of findCalls(clean, masked, 'onShowMessageAlertHandler|onShowLoadingHandler|onDismissLoadingHandler|presentToast|errToasr')) {
      overlays.push({ kind: `dbService.${c.name}`, text: collapse(c.args.join(', ')), file, line: c.line });
    }
    for (const m of clean.matchAll(/from\s+['"]@ionic-native\/([^'"]+)['"]/g)) natives.add(`${m[1]} (${file}:${lineOf(clean, m.index)})`);
    for (const c of findCalls(clean, masked, 'get|instant|stream')) {
      if (!/translate/i.test(c.recv)) continue;
      const keys = [...(c.args[0] || '').matchAll(/(['"])((?:(?!\1).)*)\1/g)].map(x => x[2]);
      for (const k of keys) i18n.push({ key: k, via: `translate.${c.name}`, file, line: c.line });
    }
  }

  // template analysis
  const hardcoded = [];
  const htmlClasses = new Set();
  for (const f of htmlFiles) {
    const raw = read(`${dir}/${f}`);
    const html = stripHtmlComments(raw);
    const file = rel(`${dir}/${f}`);
    for (const m of html.matchAll(/(['"])((?:(?!\1).)+)\1\s*\|\s*translate/g)) i18n.push({ key: m[2], via: '| translate', file, line: lineOf(html, m.index) });
    for (const m of html.matchAll(/\b(?:placeholder|title|cancelText|okText|doneText|subTitle|label|alt)\s*=\s*"([^"{]+)"/g)) {
      const t = m[1].trim();
      if (t && /[A-Za-z\u0900-\u097F]/.test(t)) hardcoded.push({ text: t, where: m[0].split('=')[0], file, line: lineOf(html, m.index) });
    }
    const noScript = html.replace(/<(script|style)[\s\S]*?<\/\1>/g, s => s.replace(/[^\n]/g, ' '));
    for (const m of noScript.matchAll(/>([^<>]+)(?=<)/g)) {
      const t = m[1].replace(/{{[\s\S]*?}}/g, ' ').replace(/&nbsp;/g, ' ').replace(/\s+/g, ' ').trim();
      if (!t || !/[A-Za-z0-9\u0900-\u097F]/.test(t)) continue;
      hardcoded.push({ text: t, where: 'text', file, line: lineOf(html, m.index + 1 + m[1].search(/\S/)) });
    }
    for (const m of html.matchAll(/\bclass\s*=\s*"([^"{]*)"/g)) m[1].split(/\s+/).filter(Boolean).forEach(c => htmlClasses.add(c));
    for (const m of html.matchAll(/\[class\.([\w-]+)\]/g)) htmlClasses.add(m[1]);
    for (const m of html.matchAll(/\[ngClass\]\s*=\s*"([^"]*)"/g)) for (const s of m[1].matchAll(/['"]([\w\s-]+)['"]/g)) s[1].split(/\s+/).filter(Boolean).forEach(c => htmlClasses.add(c));
  }

  // 2. nav params
  w('## Nav params read', '');
  if (params.length) for (const p of params) w(`- ${code(p.key)} (${p.file}:${p.line})`);
  else w('_none_');
  w('');

  // 3. endpoints
  w('## Endpoints', '');
  if (apis.length) {
    w('| Helper | Endpoint | Server | Body source | Where |', '|---|---|---|---|---|');
    for (const a of apis) {
      let body = a.body == null ? '(none)' : a.body === '' ? "''" : clip(a.body);
      if (a.bodyDef) body += ` where ${clip(a.bodyDef.text, 260)} (line ${a.bodyDef.line})`;
      w(`| ${a.helper} | ${code(a.endpoint)} | ${a.server} | ${code(cell(body))} | ${a.file}:${a.line} |`);
    }
  } else w('_none_');
  w('');

  // 4. response fields
  w('## Response fields read', '');
  const withFields = apis.filter(a => a.response.length);
  if (withFields.length) {
    for (const a of withFields) w(`- ${code(a.endpoint)} (${a.file}:${a.line}): ${a.response.map(code).join(', ')}`);
  } else w('_none_');
  w('');

  // 5. nav targets
  w('## Nav targets', '');
  if (navs.length) {
    w('| Kind | Target | Params | Where |', '|---|---|---|---|');
    for (const n of navs) w(`| ${n.kind} | ${code(n.target.replace(/Page$/, ''))} | ${n.params ? code(cell(clip(n.params, 200))) : ''} | ${n.file}:${n.line} |`);
  } else w('_none_');
  w('');

  // 6. overlays
  w('## Overlays', '');
  if (overlays.length) {
    w('| Overlay | First argument | Where |', '|---|---|---|');
    for (const o of overlays) w(`| ${o.kind} | ${o.text ? code(cell(clip(o.text, 200))) : ''} | ${o.file}:${o.line} |`);
  } else w('_none_');
  w('');

  // 7. natives
  w('## Natives (@ionic-native)', '');
  if (natives.size) for (const n of [...natives].sort()) w(`- ${n}`);
  else w('_none_');
  w('');

  // 8. i18n
  w('## i18n keys', '');
  const seen = new Set();
  const keys = i18n.filter(k => (seen.has(k.key) ? false : seen.add(k.key)));
  if (keys.length) for (const k of keys) w(`- ${code(k.key)} (${k.via}, ${k.file}:${k.line})`);
  else w('_none_');
  w('', '## Hardcoded text', '');
  if (hardcoded.length) {
    w('| Text | Where |', '|---|---|');
    for (const h of hardcoded) w(`| ${cell(clip(h.text, 120))} | ${h.where} ${h.file}:${h.line} |`);
  } else w('_none_');
  w('');

  // 9. scss
  w('## SCSS', '');
  const pageClasses = new Set();
  if (scssFiles.length) {
    for (const f of scssFiles) {
      const txt = stripScssComments(read(`${dir}/${f}`));
      for (const m of txt.matchAll(/\.([A-Za-z_][\w-]*)/g)) pageClasses.add(m[1]);
      const vars = [...new Set([...txt.matchAll(/\$[\w-]+/g)].map(m => m[0]))];
      w(`- ${code(rel(`${dir}/${f}`))} (${lineCount(`${dir}/${f}`)} lines)${vars.length ? `; SCSS variables used: ${vars.map(code).join(', ')}` : ''}`);
    }
  } else w('_no page SCSS file_');
  const varsFile = `${src}/theme/variables.scss`;
  const globalClasses = new Set();
  if (fs.existsSync(varsFile)) {
    const txt = stripScssComments(read(varsFile));
    for (const m of txt.matchAll(/\.([A-Za-z_][\w-]*)/g)) globalClasses.add(m[1]);
  }
  const appScss = `${src}/app/app.scss`;
  const appClasses = new Set();
  if (fs.existsSync(appScss)) for (const m of stripScssComments(read(appScss)).matchAll(/\.([A-Za-z_][\w-]*)/g)) appClasses.add(m[1]);
  const usedGlobal = [...htmlClasses].filter(c => globalClasses.has(c)).sort();
  const usedApp = [...htmlClasses].filter(c => appClasses.has(c) && !globalClasses.has(c)).sort();
  const unknown = [...htmlClasses].filter(c => !globalClasses.has(c) && !appClasses.has(c) && !pageClasses.has(c)).sort();
  w('', `Global classes from \`src/theme/variables.scss\` used in the template: ${usedGlobal.length ? usedGlobal.map(code).join(', ') : '_none_'}`);
  if (usedApp.length) w('', `Classes from \`src/app/app.scss\`: ${usedApp.map(code).join(', ')}`);
  w('', `Classes used in the template that no SCSS file defines (Ionic built-ins or dynamic): ${unknown.length ? unknown.map(code).join(', ') : '_none_'}`);
  w('', `Classes defined by the page SCSS and used in the template: ${[...htmlClasses].filter(c => pageClasses.has(c)).sort().map(code).join(', ') || '_none_'}`);
  w('');

  w('## Quirks', '', '', '## States', '', '');
  void base;
  return { page, text: out.join('\n').replace(/\n{3,}/g, '\n\n').replace(/\n+$/, '\n\n') .replace(/## Quirks\n\n\n/, '## Quirks\n\n\n') };
}

// CLI
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const name = args.find(a => !a.startsWith('--') && args[args.indexOf(a) - 1] !== '--out');
  if (!name) {
    console.error('usage: node scripts/screen-card.mjs <Name> [--out <screens dir>] [--stdout]');
    process.exit(2);
  }
  const oi = args.indexOf('--out');
  const screens = oi > -1 ? path.resolve(args[oi + 1]) : path.join(ROOT, 'src/screens');
  const { page, text } = buildCard(name);
  if (args.includes('--stdout')) process.stdout.write(text);
  else {
    const dest = path.join(screens, page.name, 'card.md');
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, text);
    console.log(`screen-card: ${path.relative(ROOT, dest)}`);
  }
}
